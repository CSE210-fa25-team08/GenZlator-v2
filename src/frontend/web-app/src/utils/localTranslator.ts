// Create reverse mapping (word to emoji)
export const wordToEmoji: Record<string, string> = Object.entries(emojiToWord).reduce(
  (acc, [emoji, words]) => {
    words.forEach(word => {
        acc[word.toLowerCase()] = emoji;
    });
    return acc;
  },
  {} as Record<string, string>
);

// Helper for regex escaping
const escapeRegExp = (string: string) => string.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');

// Pre-compute regex for performance - matches longest phrases first
const emojiKeywords = Object.keys(wordToEmoji).sort((a, b) => b.length - a.length);
// Use word boundaries to prevent partial matches (e.g. "hot" matching inside "hotel")
const emojiPattern = new RegExp(`\\b(${emojiKeywords.map(escapeRegExp).join('|')})\\b`, 'gi');

