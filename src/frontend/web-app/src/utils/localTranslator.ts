// Translate emojis to text
export const translateToWords = (text: string): string => {
  if (!text.trim()) return '';

  // Match emojis using regex
  const emojiRegex = /[\u{1F300}-\u{1F9FF}]|[\u{2600}-\u{26FF}]|[\u{2700}-\u{27BF}]/gu;

  return text.replace(emojiRegex, (emoji) => {
    const words = emojiToWord[emoji];
    return words && words.length > 0 ? ` ${words[0]} ` : emoji;
  }).replace(/\s+/g, ' ').trim();
};
